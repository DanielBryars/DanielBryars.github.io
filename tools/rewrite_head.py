def canonical_for(page: Path) -> str:
    rel = page.relative_to(REPO).as_posix()
    if rel == "index.html":
        return f"{SITE}/"
    if rel.endswith("/index.html"):
        return f"{SITE}/{rel[: -len('index.html')]}"
    return f"{SITE}/{rel}"


def build_block(page: Path, title: str, description: str) -> str:
    rel = page.relative_to(REPO).as_posix()
    image = PAGE_IMAGES.get(rel, "images/og-cover.jpg")
    root = rel_url(page, REPO / "x")[:-1]  # relative prefix back to the repo root

    lines = [
        START,
        f'    <link rel="canonical" href="{canonical_for(page)}">',
        f'    <link rel="icon" href="{root}favicon.svg" type="image/svg+xml">',
        f'    <link rel="apple-touch-icon" href="{root}images/apple-touch-icon.png">',
        '    <meta name="theme-color" content="#10120f">',
        '    <meta name="author" content="Daniel Bryars">',
        '    <meta property="og:type" content="website">',
        '    <meta property="og:site_name" content="Daniel Bryars">',
        f'    <meta property="og:url" content="{canonical_for(page)}">',
        f'    <meta property="og:title" content="{escape(title, quote=True)}">',
        f'    <meta property="og:description" content="{escape(description, quote=True)}">',
        f'    <meta property="og:image" content="{SITE}/{image}">',
        '    <meta name="twitter:card" content="summary_large_image">',
        f'    <meta name="twitter:title" content="{escape(title, quote=True)}">',
        f'    <meta name="twitter:description" content="{escape(description, quote=True)}">',
        f'    <meta name="twitter:image" content="{SITE}/{image}">',
    ]
    if rel == "index.html":
        lines.append(PERSON_JSONLD.rstrip("\n"))
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    changed = 0
    for page in html_files():
        text = page.read_text(encoding="utf-8")

        title_match = TITLE_RE.search(text)
        desc_match = DESC_RE.search(text)
        if not title_match:
            print(f"  skip (no <title>): {page.relative_to(REPO)}")
            continue
        if not desc_match:
            print(f"  !! no meta description: {page.relative_to(REPO)}")
            continue

        title = unescape(title_match.group(1).strip())
        description = unescape(desc_match.group(1).strip())
        block = build_block(page, title, description)

        if BLOCK_RE.search(text):
            updated = BLOCK_RE.sub(lambda _: block.strip(), text, count=1)
        else:
            # Insert straight after the description tag so the head stays readable.
            insert_at = desc_match.end()
            insert_at = text.index("\n", insert_at) + 1
            updated = text[:insert_at] + block + "\n" + text[insert_at:]

        if updated != text:
            page.write_text(updated, encoding="utf-8")
            changed += 1
            print(f"  head {page.relative_to(REPO)}")

    print(f"{changed} page(s) updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
