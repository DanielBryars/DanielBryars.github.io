"""Keep the <head> of every page consistent: icons, canonical URL, share cards.

Each page keeps its own <title> and <meta name="description"> - those are
written by hand. This script derives the social-share tags from them so a link
pasted into LinkedIn, Slack or an email renders properly instead of as a blank
grey box.

The generated block is fenced by HTML comments and replaced wholesale on every
run, so this is safe to re-run after adding new pages:

    python tools/rewrite_head.py
"""

