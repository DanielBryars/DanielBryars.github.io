START = "    <!-- head:meta - generated by tools/rewrite_head.py -->"
END = "    <!-- /head:meta -->"

BLOCK_RE = re.compile(
    re.escape(START.strip()) + r".*?" + re.escape(END.strip()),
    re.DOTALL,
)
TITLE_RE = re.compile(r"<title>(.*?)</title>", re.DOTALL | re.IGNORECASE)
DESC_RE = re.compile(r'<meta\s+name="description"\s+content="([^"]*)"', re.IGNORECASE)

